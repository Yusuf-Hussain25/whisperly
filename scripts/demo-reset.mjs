// Demo reset tools (see api/_lib/demo-reset.js).
//
//   npm run demo:baseline   # save the demo's current chats as the state to restore (run right after npm run seed)
//   npm run demo:reset      # put the demo back to that state now (the cron does this daily)
import { readFileSync, writeFileSync } from "node:fs";
import { captureBaseline, restoreBaseline, signInAsDemo } from "../api/_lib/demo-reset.js";

const env = Object.fromEntries(
    readFileSync(new URL("../.env", import.meta.url), "utf8")
        .split("\n")
        .filter((line) => line.includes("=") && !line.trim().startsWith("#"))
        .map((line) => [line.slice(0, line.indexOf("=")).trim(), line.slice(line.indexOf("=") + 1).trim().replace(/^"|"$/g, "")])
);

const command = process.argv[2];
const { db, uid, close } = await signInAsDemo(env);
try {
    if (command === "baseline") {
        const baseline = await captureBaseline(db, uid);
        const file = new URL("../api/_lib/demo-baseline.js", import.meta.url);
        writeFileSync(file, `// Generated by \`npm run demo:baseline\`. The demo's seeded chats, restored daily.\nexport default ${JSON.stringify(baseline, null, 2)};\n`);
        console.log(`Saved ${baseline.chats.length} chats and ${Object.values(baseline.conversations).reduce((n, c) => n + c.messages.length, 0)} messages.`);
    } else if (command === "reset") {
        const { default: baseline } = await import("../api/_lib/demo-baseline.js");
        console.log(await restoreBaseline(db, baseline));
    } else {
        console.error("Usage: node scripts/demo-reset.mjs baseline|reset");
        process.exitCode = 1;
    }
} finally {
    await close();
}
